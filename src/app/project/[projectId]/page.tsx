// Script Panel (with Edit Mode)
// ============================================================
function ScriptPanel({
  script,
  isGenerating,
  progress,
  onGenerate,
  onApprove,
}: {
  script: any;
  isGenerating: boolean;
  progress: number;
  onGenerate: () => void;
  onApprove: () => void;
}) {
  const [isEditing, setIsEditing] = useState(false);
  const [editedFullScript, setEditedFullScript] = useState("");
  const [saveError, setSaveError] = useState<string | null>(null);

  // Sync edited text when script changes
  useEffect(() => {
    if (script && !isEditing) {
      setEditedFullScript(script.fullScript || "");
    }
  }, [script, isEditing]);

  const handleSaveEdit = async () => {
    if (!script) return;
    setSaveError(null);

    // Update the script with edited content
    const updatedScript = {
      ...script,
      fullScript: editedFullScript,
      scenes: parseScenesFromScript(editedFullScript, script.scenes),
    };

    // 1. Update Zustand state (client)
    useProjectStore.getState().setScriptResult(updatedScript);

    // 2. Persist ke database via PATCH /api/projects
    const project = useProjectStore.getState().currentProject;
    if (!project) {
      setSaveError("Project tidak ditemukan. Perubahan hanya tersimpan di sesi ini.");
      return;
    }

    try {
      const res = await fetch("/api/projects", {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          projectId: project.id,
          script: updatedScript,
        }),
      });
      const json = await res.json();
      if (!res.ok || !json.success) {
        // Jangan hapus perubahan lokal — tampilkan error jelas
        setSaveError(json.error || `Gagal menyimpan script (HTTP ${res.status})`);
        return;
      }
    } catch (err) {
      // Jangan hapus perubahan lokal — tampilkan error jelas
      setSaveError(err instanceof Error ? err.message : "Gagal menyimpan script ke database");
      return;
    }

    setIsEditing(false);
  };

  return (
    <Card>
      <CardHeader className="flex flex-row items-center justify-between">
        <CardTitle className="text-lg">Script Generator</CardTitle>
        <div className="flex items-center gap-2">
          {script && !isEditing && (
            <>
              <Button variant="outline" size="sm" onClick={() => setIsEditing(true)} className="gap-1">
                <Edit3 className="h-3.5 w-3.5" />
                Edit
              </Button>
              <Button variant="outline" size="sm" onClick={onGenerate} disabled={isGenerating} className="gap-1">
                <RefreshCw className="h-3.5 w-3.5" />
                Regenerate
              </Button>
            </>
          )}
          {isEditing && (
            <Button size="sm" onClick={handleSaveEdit} className="gap-1">
              <Save className="h-3.5 w-3.5" />
              Simpan
            </Button>
          )}
          {!script && !isGenerating && (
            <Button size="sm" onClick={onGenerate} className="gap-1">
              <Sparkles className="h-3.5 w-3.5" />
              Generate Script
            </Button>
          )}
        </div>
      </CardHeader>
      <CardContent>
        {isGenerating ? (
          <div className="space-y-4 py-8">
            <div className="flex items-center justify-center">
              <Loader2 className="h-8 w-8 animate-spin text-primary" />
            </div>
            <div className="space-y-2">
              <Progress value={progress} className="h-2" />
              <p className="text-center text-sm text-muted-foreground">Menulis script...</p>
            </div>
          </div>
        ) : script ? (
          <div className="space-y-4">
            {isEditing ? (
              <div className="space-y-2">
                <div className="flex items-center justify-between">
                  <h3 className="font-semibold">{script.title}</h3>
                  <Badge variant="warning">Mode Edit</Badge>
                </div>
                <textarea
                  value={editedFullScript}
                  onChange={(e) => setEditedFullScript(e.target.value)}
                  className="w-full h-80 p-3 rounded-lg border border-input bg-background text-sm font-mono resize-y"
                />
                <p className="text-xs text-muted-foreground">
                  Edit teks script secara manual. Setiap baris baru akan menjadi scene baru.
                </p>
                {saveError && (
                  <div className="flex items-start gap-2 p-3 rounded-lg border border-destructive bg-destructive/5 text-sm text-destructive">
                    <AlertCircle className="h-4 w-4 mt-0.5 shrink-0" />
                    <span>{saveError}</span>
                  </div>
                )}
              </div>
            ) : (
              <>
                <div className="flex items-center justify-between">
                  <div className="min-w-0">
                    <h3 className="font-semibold truncate">{script.title}</h3>
                    <p className="text-xs text-muted-foreground">
                      {script.wordCount} kata • estimasi {script.estimatedDuration} detik
                    </p>
                  </div>
                  <Badge variant="success" className="shrink-0">Selesai</Badge>
                </div>
                <Separator />
                <div className="max-h-96 overflow-y-auto space-y-3">
                  {script.scenes?.map((scene: Scene) => (
                    <div key={scene.id} className="space-y-1 p-3 rounded-lg bg-muted/50">
                      <div className="flex items-center justify-between">
                        <h4 className="text-sm font-medium">{scene.heading}</h4>
                        <span className="text-xs text-muted-foreground shrink-0">{scene.duration}s</span>
                      </div>
                      <p className="text-sm text-muted-foreground">{scene.content}</p>
                      {scene.visualPrompt && (
                        <p className="text-xs text-muted-foreground/70 italic">
                          🎬 {scene.visualPrompt}
                        </p>
                      )}
                    </div>
                  ))}
                </div>
              </>
            )}
            <div className="flex justify-end pt-2">
              <Button onClick={onApprove} className="gap-2">
                <CheckCircle2 className="h-4 w-4" />
                Lanjut ke Audio
              </Button>
            </div>
          </div>
        ) : (
          <div className="flex flex-col items-center justify-center py-12 text-center">
            <FileText className="h-12 w-12 text-muted-foreground/30 mb-4" />
            <p className="text-muted-foreground mb-2">Menulis script...</p>
            <p className="text-xs text-muted-foreground/70">
              Script akan digenerate secara otomatis
            </p>
          </div>
        )}
      </CardContent>
    </Card>
  );
}

