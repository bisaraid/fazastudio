// Video Panel — Composition Preview (footage + audio + subtitle)
// ============================================================
function VideoPanel({
  video,
  project,
  isGenerating,
  progress,
  onGenerate,
  onApprove,
}: {
  video: any;
  project: any;
  isGenerating: boolean;
  progress: number;
  onGenerate: () => void;
  onApprove: () => void;
}) {
  const [isEditing, setIsEditing] = useState(false);
  const [editStyle, setEditStyle] = useState<VisualStyle>("stock");
  // Footage selection state
  const [footageOptions, setFootageOptions] = useState<any[]>([]);
  const [isFootageLoading, setIsFootageLoading] = useState(false);
  const [selectedFootageId, setSelectedFootageId] = useState<string | null>(
    project?.footage?.id || null
  );
  // Timeline: footage per scene
  const [sceneFootage, setSceneFootage] = useState<{ sceneId: string; videoUrl: string }[]>([]);
  const handleTimelineRender = (list: { sceneId: string; videoUrl: string }[]) => {
    setSceneFootage(list);
    onGenerate();
  };
  // Audio playback
  const audioRef = useRef<HTMLAudioElement>(null);
  const [isPlaying, setIsPlaying] = useState(false);
  const [audioError, setAudioError] = useState<string | null>(null);
  // Audio preview via proxy (server-side fetch + range support)
  const audioProxyUrl = useAudioProxyUrl(project?.audio?.url);
  // Video preview via proxy — fix CORS/range di <video>
  const videoProxyUrl = useVideoProxyUrl(video?.url);
  // Subtitle caption/style editing (localhost — tidak trigger TTS/transcription)
  const segments = project?.subtitle?.segments || [];
  const style = project?.subtitle?.style || {
    fontSize: 28,
    color: "#FFD700",
    position: "bottom",
    strokeColor: "#000000",
    strokeWidth: 2,
  };

  useEffect(() => {
    if (video && !isEditing) {
      setEditStyle("stock");
    }
  }, [video, isEditing]);

  // Derive query visual untuk pencarian footage
  const getFootageQuery = () => {
    const sceneWithPrompt = project?.script?.scenes?.find((s: any) => s.visualPrompt);
    return sceneWithPrompt?.visualPrompt || project?.topic || "";
  };

  const handleFetchFootage = async () => {
    setIsFootageLoading(true);
    try {
      const res = await fetch("/api/footage", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          query: getFootageQuery(),
          genre: project?.genre,
          perPage: 6,
        }),
      });
      const json = await res.json();
      if (json.success && Array.isArray(json.data)) {
        setFootageOptions(json.data);
      } else if (json.error) {
        console.error("[VideoPanel] Footage error:", json.error);
      }
    } catch (err) {
      console.error("[VideoPanel] Fetch footage gagal:", err);
    } finally {
      setIsFootageLoading(false);
    }
  };

  const handleSelectFootage = (footage: any) => {
    setSelectedFootageId(footage.id);
    useProjectStore.getState().setFootageResult(footage);
  };

  const selectedFootage = project?.footage || footageOptions.find((f) => f.id === selectedFootageId);

  // Edit caption text (tidak trigger TTS — hanya update subtitle state + re-render)
  const handleEditCaption = (segId: string, newText: string) => {
    if (!project?.subtitle) return;
    const updatedSegments = segments.map((s: any) =>
      s.id === segId ? { ...s, text: newText } : s
    );
    useProjectStore.getState().setSubtitleResult({
      ...project.subtitle,
      segments: updatedSegments,
      entries: updatedSegments.map((s: any) => ({
        id: s.id, startTime: s.startTime, endTime: s.endTime, text: s.text,
      })),
    });
  };

  // Edit style dasar (tidak trigger TTS — hanya update subtitle state + re-render)
  // Mendukung: fontSize, color, position, strokeColor, strokeWidth, backgroundColor, backgroundAlpha
  const handleStyleChange = (patch: Partial<NonNullable<typeof style>>) => {
    if (!project?.subtitle) return;
    useProjectStore.getState().setSubtitleResult({
      ...project.subtitle,
      style: { ...style, ...patch },
    });
  };

  const togglePlay = () => {
    if (!audioRef.current) return;
    if (isPlaying) audioRef.current.pause();
    else audioRef.current.play();
    setIsPlaying(!isPlaying);
  };
  useEffect(() => {
    const el = audioRef.current;
    if (!el) return;
    const onEnded = () => setIsPlaying(false);
    el.addEventListener("ended", onEnded);
    return () => el.removeEventListener("ended", onEnded);
  }, [audioRef.current]);

  return (
    <Card>
      <CardHeader className="flex flex-row items-center justify-between">
        <CardTitle className="text-lg">Video</CardTitle>
        {video && !isGenerating && (
          <Button variant="outline" size="sm" onClick={onGenerate} className="gap-1">
            <RefreshCw className="h-3.5 w-3.5" />
            Render Lagi
          </Button>
        )}
      </CardHeader>
      <CardContent className="space-y-6">
        {/* ===== PLATFORM (read-only) ===== */}
        <div className="space-y-1">
          <label className="text-sm font-medium">Platform</label>
          <div className="flex flex-wrap gap-2">
            {Object.entries(PLATFORM_CONFIG).map(([key, config]) => {
              const isActive = project?.platform === key;
              return (
                <div
                  key={key}
                  className={`flex h-11 items-center rounded-full px-5 text-sm font-medium ${
                    isActive
                      ? "bg-primary text-primary-foreground"
                      : "border border-border text-muted-foreground"
                  }`}
                >
                  {config.label}
                </div>
              );
            })}
          </div>
          <p className="text-xs text-muted-foreground">
            Untuk mengubah platform atau durasi, buat proyek baru
          </p>
        </div>

{/* ===== KUSTOMISASI FOOTAGE (collapsed, sistem auto-pilih) ===== */}
        <TimelineEditor
          project={project}
          isGenerating={isGenerating}
          progress={progress}
          onRender={handleTimelineRender}
        />

        {/* ===== RENDER ACTION (tunggal) ===== */}
        {isGenerating ? (
          <>
            <div className="w-full h-14 flex items-center justify-center gap-2 rounded-xl bg-primary text-primary-foreground">
              <Loader2 className="h-5 w-5 animate-spin" />
              Merender... {Math.round(progress)}%
            </div>
            <Progress value={progress} className="h-2 w-full" />
          </>
        ) : video ? (
          <>
            <div className="w-full h-14 flex items-center justify-center gap-2 rounded-xl bg-emerald-500/10 text-emerald-600 text-sm font-semibold">
              ✅ Video Selesai
            </div>
            <div className="rounded-lg overflow-hidden border border-border bg-black">
              <video
                src={videoProxyUrl || video.url}
                controls
                className="w-full aspect-video object-contain"
                poster={video.thumbnailUrl}
                onError={(e) => {
                  const el = e.currentTarget;
                  if (el.src !== video.url) {
                    el.src = video.url;
                    el.load();
                  }
                }}
              />
            </div>
            <div className="grid grid-cols-2 gap-3">
              {project?.audio?.url && (
                <a
                  href={project.audio.url}
                  download="faza-studio-audio.mp3"
                  className="inline-flex h-12 items-center justify-center gap-2 rounded-lg border border-input bg-background text-sm font-medium hover:bg-accent"
                >
                  <Download className="h-4 w-4" />
                  Unduh Audio
                </a>
              )}
              <a
                href={video.url}
                download={`${project.title || "video"}.mp4`}
                className="inline-flex h-12 items-center justify-center gap-2 rounded-lg bg-primary px-3 text-sm font-medium text-primary-foreground hover:bg-primary/90"
              >
                <Download className="h-4 w-4" />
                Unduh Video
              </a>
            </div>
          </>
        ) : (
          <Button onClick={onGenerate} className="w-full h-14 gap-2">
            🎬 Render Video
          </Button>
        )}
      </CardContent>
    </Card>
  );
}

