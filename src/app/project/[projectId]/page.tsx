// Subtitle Panel (with Edit Mode)
// ============================================================
function SubtitlePanel({
  subtitle,
  isGenerating,
  progress,
  onGenerate,
  onApprove,
}: {
  subtitle: any;
  isGenerating: boolean;
  progress: number;
  onGenerate: () => void;
  onApprove: () => void;
}) {
  const [isEditing, setIsEditing] = useState(false);
  const [editedEntries, setEditedEntries] = useState<SubtitleEntry[]>([]);

  useEffect(() => {
    if (subtitle && !isEditing) {
      setEditedEntries(subtitle.entries || []);
    }
  }, [subtitle, isEditing]);

  const handleEditText = (id: string, newText: string) => {
    setEditedEntries((prev) =>
      prev.map((entry) => (entry.id === id ? { ...entry, text: newText } : entry))
    );
  };

  const handleSaveEdit = () => {
    if (subtitle) {
      const updatedSubtitle = {
        ...subtitle,
        entries: editedEntries,
        srtContent: generateSrtFromEntries(editedEntries),
        vttContent: generateVttFromEntries(editedEntries),
      };
      useProjectStore.getState().setSubtitleResult(updatedSubtitle);
    }
    setIsEditing(false);
  };

  return (
    <Card>
      <CardHeader className="flex flex-row items-center justify-between">
        <CardTitle className="text-lg">Subtitle</CardTitle>
        <div className="flex items-center gap-2">
          {subtitle && !isEditing && (
            <>
              <Button variant="outline" size="sm" onClick={() => setIsEditing(true)} className="gap-1">
                <Edit3 className="h-3.5 w-3.5" />
                Edit
              </Button>
              <Button variant="ghost" size="sm" onClick={onGenerate} disabled={isGenerating} className="gap-1">
                <RefreshCw className="h-3.5 w-3.5" />
                Buat Ulang
              </Button>
            </>
          )}
          {isEditing && (
            <Button size="sm" onClick={handleSaveEdit} className="gap-1">
              <Save className="h-3.5 w-3.5" />
              Simpan
            </Button>
          )}
          {!subtitle && !isGenerating && (
            <Button size="sm" onClick={onGenerate} className="gap-1">
              <Sparkles className="h-3.5 w-3.5" />
              Buat Subtitle
            </Button>
          )}
        </div>
      </CardHeader>
      <CardContent>
        {isGenerating ? (
          <div className="space-y-4 py-8">
            <div className="flex items-center justify-center">
              <Loader2 className="h-8 w-8 animate-spin text-primary" />
            </div>
            <div className="space-y-2">
              <Progress value={progress} className="h-2" />
              <p className="text-center text-sm text-muted-foreground">Sinkronisasi subtitle...</p>
            </div>
          </div>
        ) : subtitle ? (
          <div className="space-y-4">
            {isEditing && <Badge variant="warning">Mode Edit</Badge>}
            <div className="max-h-60 overflow-y-auto space-y-1">
              {(isEditing ? editedEntries : subtitle.entries)?.map((entry: SubtitleEntry) => (
                <div key={entry.id} className="flex items-start gap-2 p-2 rounded text-sm hover:bg-muted/50">
                  <span className="text-xs text-muted-foreground w-12 shrink-0 font-mono">
                    {formatTime(entry.startTime)}
                  </span>
                  {isEditing ? (
                    <input
                      type="text"
                      value={editedEntries.find((e) => e.id === entry.id)?.text || entry.text}
                      onChange={(e) => handleEditText(entry.id, e.target.value)}
                      className="flex-1 px-2 py-0.5 rounded border border-input bg-background text-sm"
                    />
                  ) : (
                    <span className="flex-1">{entry.text}</span>
                  )}
                  <span className="text-xs text-muted-foreground w-12 shrink-0 text-right font-mono">
                    {formatTime(entry.endTime)}
                  </span>
                </div>
              ))}
            </div>
            <div className="flex justify-end pt-2">
              <Button onClick={onApprove} className="gap-2">
                <CheckCircle2 className="h-4 w-4" />
                Lanjut ke Video
              </Button>
            </div>
          </div>
        ) : (
          <div className="flex flex-col items-center justify-center py-12 text-center">
            <Subtitles className="h-12 w-12 text-muted-foreground/30 mb-4" />
            <p className="text-muted-foreground mb-2">Menyiapkan subtitle...</p>
            <p className="text-xs text-muted-foreground/70">
              Subtitle akan digenerate setelah audio selesai
            </p>
          </div>
        )}
      </CardContent>
    </Card>
  );
}

