function formatTime(seconds: number): string {
  const m = Math.floor(seconds / 60);
  const s = Math.floor(seconds % 60);
  return `${m}:${s.toString().padStart(2, "0")}`;
}

function parseScenesFromScript(fullScript: string, originalScenes: Scene[]): Scene[] {
  const lines = fullScript.split("\n\n").filter((l) => l.trim());
  if (lines.length === 0) return originalScenes;

  return lines.map((line, i) => {
    const existing = originalScenes[i];
    const parts = line.split("\n");
    const heading = parts[0] || `Bagian ${i + 1}`;
    const content = parts.slice(1).join("\n") || parts[0] || "";

    return {
      id: existing?.id || generateId(),
      order: i + 1,
      heading,
      content,
      visualPrompt: existing?.visualPrompt,
      duration: existing?.duration || 30,
    };
  });
}

function generateSrtFromEntries(entries: SubtitleEntry[]): string {
  return entries
    .map((e, i) => {
      const start = formatSrtTime(e.startTime);
      const end = formatSrtTime(e.endTime);
      return `${i + 1}\n${start} --> ${end}\n${e.text}`;
    })
    .join("\n\n");
}

function generateVttFromEntries(entries: SubtitleEntry[]): string {
  return `WEBVTT\n\n${entries
    .map((e) => {
      const start = formatSrtTime(e.startTime);
      const end = formatSrtTime(e.endTime);
      return `${start} --> ${end}\n${e.text}`;
    })
    .join("\n\n")}`;
}

function formatSrtTime(seconds: number): string {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = Math.floor(seconds % 60);
  const ms = Math.floor((seconds % 1) * 1000);
  return `${h.toString().padStart(2, "0")}:${m.toString().padStart(2, "0")}:${s
    .toString()
    .padStart(2, "0")},${ms.toString().padStart(3, "0")}`;
}