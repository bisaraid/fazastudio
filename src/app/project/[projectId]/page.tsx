/**
 * Prioritaskan `/api/audio-proxy?url=<encoded-supabase-url>` sebagai source audio preview.
 * project.audio.url TETAP Supabase URL untuk backend/subtitle/download.
 */
function useAudioProxyUrl(audioUrl: string | null | undefined): string | null {
  const [proxyUrl, setProxyUrl] = useState<string | null>(null);

  useEffect(() => {
    if (!audioUrl) {
      setProxyUrl(null);
      return;
    }

    // Prioritaskan proxy URL (server-side fetch + range support)
    const proxy = `/api/audio-proxy?url=${encodeURIComponent(audioUrl)}`;
    setProxyUrl(proxy);

    // Fallback: fetch → blob → object URL (hanya jika proxy gagal)
    let objectUrl: string | null = null;
    let cancelled = false;

    const tryFetchBlob = async () => {
      try {
        const res = await fetch(audioUrl);
        if (!res.ok || cancelled) return;
        const blob = await res.blob();
        if (cancelled) return;
        objectUrl = URL.createObjectURL(blob);
      } catch {
        // ignore — proxy is primary
      }
    };

    tryFetchBlob();

    return () => {
      cancelled = true;
      if (objectUrl) {
        URL.revokeObjectURL(objectUrl);
      }
    };
  }, [audioUrl]);

  return proxyUrl;
}

